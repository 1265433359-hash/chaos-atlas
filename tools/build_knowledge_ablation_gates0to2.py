def run_leakage_audit(project_id: str, phase: str, arm: str, bundle: dict[str, Any],
                      prompt_text: str) -> dict[str, Any]:
    p = PROJECTS[project_id]
    sections = bundle["sections"]
    results: dict[str, Any] = {"project": project_id, "phase": phase, "arm": arm, "scans": []}

    results["whole_bundle_forbidden_fields"] = find_forbidden_fields(bundle, FORBIDDEN_FIELDS)

    def scan(name: str, text: str, terms: list[str], obj: Any = None, fields: list[str] | None = None) -> None:
        hits = scan_terms(text, terms)
        field_hits = find_forbidden_fields(obj, fields) if obj is not None else []
        results["scans"].append({"section": name, "term_hits": hits, "forbidden_fields": field_hits})

    # Every arm: descriptors must be neutral (no oracle/evidence fields, no
    # historical terms, no narrow markers).
    scan("candidate_descriptors", json_text(sections["candidate_descriptors"]),
         HISTORICAL_TERMS + NARROW_MARKERS, sections["candidate_descriptors"], FORBIDDEN_FIELDS)

    if arm == "LLM-blind":
        assert sections["knowledge"] is None, "blind arm must carry no knowledge"
        scan("knowledge", "", CONTRACT_TERMS + AVAILABILITY_TERMS + KNOWLEDGE_MARKERS +
             PROJECT_TERMS[project_id] + HISTORICAL_TERMS + NARROW_MARKERS)
        scan("project_intake_summary", json_text(sections["project_intake_summary"]),
             CONTRACT_TERMS + AVAILABILITY_TERMS + KNOWLEDGE_MARKERS + HISTORICAL_TERMS + NARROW_MARKERS)
    elif arm == "LLM-generic":
        assert sections["knowledge"] is not None
        scan("knowledge", json_text(sections["knowledge"]),
             PROJECT_TERMS[project_id] + HISTORICAL_TERMS + NARROW_MARKERS + EVIDENCE_MARKERS,
             sections["knowledge"], FORBIDDEN_FIELDS)
        scan("project_intake_summary", json_text(sections["project_intake_summary"]),
             CONTRACT_TERMS + AVAILABILITY_TERMS + KNOWLEDGE_MARKERS + HISTORICAL_TERMS + NARROW_MARKERS)
    else:  # LLM-full-pre / LLM-partial-pre
        k = sections["knowledge"]
        assert isinstance(k, dict) and "generic_rules" in k and "project_specific" in k
        scan("knowledge.generic_rules", json_text(k["generic_rules"]),
             PROJECT_TERMS[project_id] + HISTORICAL_TERMS + NARROW_MARKERS + EVIDENCE_MARKERS,
             k["generic_rules"], FORBIDDEN_FIELDS)
        scan("knowledge.project_specific", json_text(k["project_specific"]),
             HISTORICAL_TERMS + NARROW_MARKERS, k["project_specific"], FORBIDDEN_FIELDS)
        scan("project_intake_summary", json_text(sections["project_intake_summary"]),
             HISTORICAL_TERMS + NARROW_MARKERS)

    scan("rendered_prompt", prompt_text, HISTORICAL_TERMS + NARROW_MARKERS)
    ok = (not results["whole_bundle_forbidden_fields"]
          and all(not e["term_hits"] and not e["forbidden_fields"] for e in results["scans"]))
    results["pass"] = ok
    return results


