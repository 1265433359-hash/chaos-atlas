    """Return (pool candidate records in registration order, classification map).

    classification[candidate_id] = (class, rule_id, evidence_refs)
    Classification is OUT-OF-BAND: it never enters any LLM bundle.
    """
    p = PROJECTS[project_id]
    snap = load_json(HELDOUT / p["snapshot_file"])
    contracts = snap.get("contract", {}).get("contracts", {})
    intake = load_json(HELDOUT / p["intake_file"])
    intake_ref = f"heldout/{p['intake_file']}"
    snap_ref = f"heldout/{p['snapshot_file']}"

    candidates: list[dict[str, Any]] = []
    classification: dict[str, tuple[str, str, list[str]]] = {}

    for family in p["supported_families"]:
        if family == "kill":
            continue
        for edge_key, _src, dst, ck in p["edges"]:
            cid = candidate_id_for_edge(project_id, edge_key, family)
            evidence = [f"{intake_ref}#dependency_graph"]
