def verify_gate0(protocol_sha: str) -> None:
    for rel, expected in PINNED_KNOWLEDGE_SHA.items():
        actual = sha256_file(f"artifacts/experiments/{rel}")
        if actual != expected:
            raise RuntimeError(f"FAIL-CLOSED: knowledge library drift {rel}: expected {expected}, got {actual}")
    actual_gr = sha256_file(GENERIC_RULES_FILE)
    if actual_gr != GENERIC_RULES_SHA:
        raise RuntimeError(f"FAIL-CLOSED: generic rules drift {GENERIC_RULES_FILE}: expected {GENERIC_RULES_SHA}, got {actual_gr}")
    for pname, p in PROJECTS.items():
        snap = load_json(HELDOUT / p["snapshot_file"])
        validate_knowledge_snapshot(snap)
        for rel, _expected in PINNED_KNOWLEDGE_SHA.items():
            stem = rel.removesuffix(".json")
            if json_text(snap[stem]) != json_text(load_json(EXPERIMENTS / rel)):
                raise RuntimeError(f"FAIL-CLOSED: {pname} snapshot embedded {stem} does not match pinned live file")
        intake = load_json(HELDOUT / p["intake_file"])
        if intake["canonical_source"]["commit"] != p["commit"]:
            raise RuntimeError(f"FAIL-CLOSED: {pname} intake commit mismatch")
        if snap["provenance"]["source_commit"] != p["commit"]:
            raise RuntimeError(f"FAIL-CLOSED: {pname} snapshot source_commit mismatch")
        if snap.get("status") != p["snapshot_status"]:
            raise RuntimeError(f"FAIL-CLOSED: {pname} snapshot expected status={p['snapshot_status']}, got {snap.get('status')}")
        if snap.get("full_pre") != p["snapshot_full_pre"]:
            raise RuntimeError(f"FAIL-CLOSED: {pname} snapshot expected full_pre={p['snapshot_full_pre']}, got {snap.get('full_pre')}")
        # Contract edges recorded in the snapshot must be the source of truth for
        # the pool universe; any edge explicitly marked unverified must NOT be used.
        unverified = snap.get("contract", {}).get("unverified_contract_edges") or []
        for ue in unverified:
            for _, _, _, ck in p["edges"]:
                if ck == ue:
                    raise RuntimeError(f"FAIL-CLOSED: {pname} uses unverified contract edge {ue}")
        for f, h in intake["sha256"].items():
            if not h or h in ("unavailable", "unknown"):
                raise RuntimeError(f"FAIL-CLOSED: {pname} intake records unavailable hash for {f}")
    print("Gate 0: snapshots schema-valid; pinned SE/DP/JE + generic-rules hashes intact; commits consistent.")


