def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def sha256_file(rel: str) -> str:
    path = ROOT / rel
    if not path.exists():
        raise FileNotFoundError(rel)
    return sha256_bytes(path.read_bytes())


def load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")


def norm_token(s: str) -> str:
    """Normalize a service name into a candidate-ID-safe token."""
    return s.lower().replace(".", "-").replace("->", "-").replace(" ", "")


def candidate_id_for_edge(project: str, edge_key: str, family: str) -> str:
    return f"{project}-{norm_token(edge_key)}-{family}"


def candidate_id_for_kill(project: str, service: str) -> str:
    return f"{project}-kill-{norm_token(service)}"


def seeded_permutation(n: int, seed: int) -> list[int]:
    """Fisher-Yates over registration-order indices [0..n-1], seeded."""
    rng = random.Random(seed)
    idx = list(range(n))
    for i in range(n - 1, 0, -1):
        j = rng.randint(0, i)
        idx[i], idx[j] = idx[j], idx[i]
    return idx


def json_text(obj: Any) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False)


def scan_terms(text: str, terms: list[str]) -> dict[str, int]:
    """Case-insensitive word-boundary term scan. Uses regex word boundaries so
    a term like 'otel' does not match the substring inside 'hotel'."""
    import re
    lower = text.lower()
    hits: dict[str, int] = {}
    for t in terms:
        pat = r"\b" + re.escape(t.lower()) + r"\b"
        c = len(re.findall(pat, lower))
        if c:
            hits[t] = c
    return hits


def find_forbidden_fields(obj: Any, forbidden: list[str], path: str = "$") -> list[str]:
    found: list[str] = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k in forbidden:
                found.append(f"{path}.{k}")
            found += find_forbidden_fields(v, forbidden, f"{path}.{k}")
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            found += find_forbidden_fields(v, forbidden, f"{path}[{i}]")
    return found


